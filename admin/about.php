// Load Dolibarr environment
$res = 0;
if (!$res && !empty($_SERVER['CONTEXT_DOCUMENT_ROOT'])) {
	$res = @include $_SERVER['CONTEXT_DOCUMENT_ROOT'].'/main.inc.php';
}
$tmp = empty($_SERVER['SCRIPT_FILENAME']) ? '' : $_SERVER['SCRIPT_FILENAME'];
$tmp2 = realpath(__FILE__);
$i = strlen($tmp) - 1;
$j = strlen($tmp2) - 1;
while ($i > 0 && $j > 0 && isset($tmp[$i]) && isset($tmp2[$j]) && $tmp[$i] == $tmp2[$j]) {
	$i--;
	$j--;
}
if (!$res && $i > 0 && file_exists(substr($tmp, 0, ($i + 1)).'/main.inc.php')) {
	$res = @include substr($tmp, 0, ($i + 1)).'/main.inc.php';
}
if (!$res && $i > 0 && file_exists(dirname(substr($tmp, 0, ($i + 1))).'/main.inc.php')) {
	$res = @include dirname(substr($tmp, 0, ($i + 1))).'/main.inc.php';
}
if (!$res && file_exists('../../main.inc.php')) {
	$res = @include '../../main.inc.php';
}
if (!$res && file_exists('../../../main.inc.php')) {
	$res = @include '../../../main.inc.php';
}
if (!$res) {
	die('Include of main fails');
}

require_once DOL_DOCUMENT_ROOT.'/core/lib/admin.lib.php';
require_once DOL_DOCUMENT_ROOT.'/core/lib/functions2.lib.php';
require_once __DIR__.'/../lib/markautomecanik.lib.php';
require_once __DIR__.'/../core/modules/modMarkAutoMecanik.class.php';

$langs->loadLangs(array('admin', 'markautomecanik@markautomecanik'));

if (!$user->admin) {
	accessforbidden();
}

llxHeader('', $langs->trans('About'), '', '', 0, 0, '', '', '', 'mod-markautomecanik page-admin-about');

$linkback = '<a href="'.DOL_URL_ROOT.'/admin/modules.php?restore_lastsearch_values=1">'.$langs->trans('BackToModuleList').'</a>';
print load_fiche_titre($langs->trans('MarkAutoMecanikSetup'), $linkback, 'title_setup');

$head = markautomecanikAdminPrepareHead();
print dol_get_fiche_head($head, 'about', $langs->trans('ModuleMarkAutoMecanikName'), -1, 'fa-bullhorn');

$module = new modMarkAutoMecanik($db);
print '<div class="moduledesclong">';
print $module->getDescLong();
print '</div>';

print dol_get_fiche_end();
llxFooter();
$db->close();
